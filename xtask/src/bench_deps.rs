use std::fs;
use std::path::Path;

use anyhow::Result;

use crate::bench::{
    assemble, fold_of, ind, names_crypto, type_of, CryptoCase, Expectation, Mutant, CASES,
};

pub(crate) const DEPS_DIR: &str = "_deps";

const VAULT_DEP: &str = "vault = { path = \"../_deps/vault\" }";
const RELAY_DEP: &str = "relay = { path = \"../_deps/relay\" }";

fn krate(case: &CryptoCase) -> &'static str {
    case.uses[0]
        .trim_start_matches("use ")
        .split("::")
        .next()
        .unwrap_or_default()
}

fn generic_parts(case: &CryptoCase) -> Option<(Vec<String>, String, &'static str, String)> {
    let k = krate(case);
    let ty = type_of(case);
    let mut uses: Vec<String> = case
        .uses
        .iter()
        .filter_map(|u| without_item(u, ty))
        .collect();
    match case.family {
        "F-HASH" | "F-HASH-DEP" => {
            uses.push(format!("use {k}::digest::Output;"));
            Some((
                uses,
                "pub fn run<D: Digest>(msg: &[u8]) -> Output<D> {".into(),
                "D::digest(msg)",
                "let _d = vault::generic_{i}::run::<H>(msg);".into(),
            ))
        }
        "F-SYM" => {
            uses.push(if k == "aes" {
                "use aes::cipher::Key;".into()
            } else {
                format!("use {k}::aead::Key;")
            });
            Some((
                uses,
                "pub fn run<C: KeyInit>(key: &Key<C>) -> C {".into(),
                "C::new(key)",
                "let _c = vault::generic_{i}::run::<H>(&key.into());".into(),
            ))
        }
        "F-PQC" => Some((
            uses,
            "pub fn run<K: KemCore, R: rand::RngCore + rand::CryptoRng>(rng: &mut R) -> (K::DecapsulationKey, K::EncapsulationKey) {"
                .into(),
            "K::generate(rng)",
            "let (_dk, _ek) = vault::generic_{i}::run::<H, _>(&mut rng);".into(),
        )),
        _ => None,
    }
}

fn without_item(line: &str, item: &str) -> Option<String> {
    let path = line.trim_start_matches("use ").trim_end_matches(';');
    let Some((prefix, list)) = path.split_once("::{") else {
        return (!path.ends_with(&format!("::{item}"))).then(|| line.to_string());
    };
    let kept: Vec<&str> = list
        .trim_end_matches('}')
        .split(',')
        .map(str::trim)
        .filter(|i| !i.is_empty() && *i != item)
        .collect();
    match kept.as_slice() {
        [] => None,
        [one] => Some(format!("use {prefix}::{one};")),
        many => Some(format!("use {prefix}::{{{}}};", many.join(", "))),
    }
}

pub(crate) fn vault_source() -> String {
    let mut out = String::from(
        "//! Benchmark dependency: one function per family and parameter. Generated by `cargo xtask bench`; do not edit.\n",
    );
    for (i, case) in CASES.iter().enumerate() {
        let param = if case.call.contains("msg") {
            "msg"
        } else {
            "_msg"
        };
        out.push_str(&format!(
            "\n/// {} {}.\npub mod cell_{i} {{\n",
            case.family, case.parameter
        ));
        for u in case.uses {
            out.push_str(&format!("    {u}\n"));
        }
        out.push_str(&format!("\n    pub fn run({param}: &[u8]) {{\n"));
        for s in case.setup {
            out.push_str(&format!("        {s}\n"));
        }
        out.push_str(&format!("        {}\n    }}\n}}\n", case.call));
        if let Some((uses, signature, body, _)) = generic_parts(case) {
            out.push_str(&format!(
                "\n/// {} {}, generic.\npub mod generic_{i} {{\n",
                case.family, case.parameter
            ));
            for u in &uses {
                out.push_str(&format!("    {u}\n"));
            }
            out.push_str(&format!("\n    {signature}\n        {body}\n    }}\n}}\n"));
        }
    }
    out.push_str(
        "\n/// The crypto-free function `N6` calls.\npub mod plain {\n    \
         pub fn label(id: u32) -> String {\n        format!(\"item-{id}\")\n    }\n}\n",
    );
    out
}

fn vault_manifest() -> String {
    let mut deps: Vec<&str> = CASES.iter().flat_map(|c| c.dep.lines()).collect();
    deps.sort_unstable();
    deps.dedup();
    format!(
        "# Generated by `cargo xtask bench`; do not edit.\n[package]\nname = \"vault\"\n\
         version = \"0.0.0\"\nedition = \"2021\"\npublish = false\n\n[dependencies]\n{}\n",
        deps.join("\n")
    )
}

fn relay_source() -> String {
    let mut out = String::from(
        "//! Benchmark dependency: forwards to `vault`, with no crypto dependency of its own.\n\
         //! Generated by `cargo xtask bench`; do not edit.\n",
    );
    for i in 0..CASES.len() {
        out.push_str(&format!(
            "\npub mod cell_{i} {{\n    pub fn run(msg: &[u8]) {{\n        vault::cell_{i}::run(msg)\n    }}\n}}\n"
        ));
    }
    out
}

pub(crate) fn relay_manifest() -> String {
    "# Generated by `cargo xtask bench`; do not edit.\n[package]\nname = \"relay\"\n\
     version = \"0.0.0\"\nedition = \"2021\"\npublish = false\n\n[dependencies]\n\
     vault = { path = \"../vault\" }\n"
        .to_string()
}

pub(crate) fn write_deps(root: &Path) -> Result<()> {
    for (name, manifest, source) in [
        ("vault", vault_manifest(), vault_source()),
        ("relay", relay_manifest(), relay_source()),
    ] {
        let dir = root.join(DEPS_DIR).join(name);
        fs::create_dir_all(dir.join("src"))?;
        fs::write(dir.join("Cargo.toml"), manifest)?;
        fs::write(dir.join("src/lib.rs"), source)?;
    }
    Ok(())
}

fn header(mode: &str, case: &CryptoCase) -> Vec<String> {
    vec![
        format!(
            "//! Positive case: failure mode {mode}, family {}.",
            case.family
        ),
        "//! Generated by `cargo xtask bench`; do not edit.".into(),
        String::new(),
    ]
}

pub(crate) fn build_dependency_shaped(
    mode: &'static str,
    case: &CryptoCase,
    seq: usize,
) -> Result<Option<Mutant>> {
    let i = CASES
        .iter()
        .position(|c| c.family == case.family && c.parameter == case.parameter)
        .expect("a known cell");
    let (head, before, call, deps): (Vec<String>, Vec<String>, String, Vec<&'static str>) =
        match mode {
            "M8" => (
                header(mode, case),
                vec!["pub fn target(msg: &[u8]) {".into()],
                ind(1, &format!("vault::cell_{i}::run(msg);")),
                vec![VAULT_DEP],
            ),
            "M10" => (
                header(mode, case),
                vec!["pub fn target(msg: &[u8]) {".into()],
                ind(1, &format!("relay::cell_{i}::run(msg);")),
                vec![RELAY_DEP],
            ),
            "M9" => {
                let Some((_, _, _, call)) = generic_parts(case) else {
                    return Ok(None);
                };
                let mut head = header(mode, case);
                head.push(format!("use {}::{} as H;", krate(case), type_of(case)));
                head.push(String::new());
                let param = if case.family.starts_with("F-HASH") {
                    "msg"
                } else {
                    "_msg"
                };
                let mut before = vec![format!("pub fn target({param}: &[u8]) {{")];
                before.extend(case.setup.iter().map(|s| ind(1, s)));
                (
                    head,
                    before,
                    ind(1, &call.replace("{i}", &i.to_string())),
                    vec![case.dep, VAULT_DEP],
                )
            }
            _ => unreachable!(),
        };
    let (source, call_line) = assemble(&head, &before, &call, &["}".to_string()]);
    let labelled = source.lines().nth(call_line - 1).unwrap_or_default();
    if let Some(token) = names_crypto(labelled, case) {
        anyhow::bail!(
            "{mode} {} {}: labelled line names `{token}`: {labelled}",
            case.family,
            case.parameter
        );
    }
    let id = format!(
        "{mode}-{}-{}-p-{seq:04}",
        case.family,
        case.parameter.replace(' ', "")
    );
    Ok(Some(Mutant {
        fold: fold_of(&id),
        id,
        failure_mode: mode,
        family: case.family,
        parameter: case.parameter,
        polarity: "positive",
        nist_tier: Some(case.tier),
        expected: vec![Expectation {
            file: "src/lib.rs".into(),
            line: call_line,
            api: case.api,
        }],
        conservatively_mapped: false,
        deps,
        dev_deps: Vec::new(),
        source,
        extra_files: Vec::new(),
    }))
}

pub(crate) fn build_n6(index: usize, seq: usize) -> Mutant {
    let id = format!("N6-n-{seq:04}");
    Mutant {
        fold: fold_of(&id),
        id,
        failure_mode: "N",
        family: "-",
        parameter: "-",
        polarity: "negative",
        nist_tier: None,
        expected: Vec::new(),
        conservatively_mapped: false,
        deps: vec![VAULT_DEP],
        dev_deps: Vec::new(),
        source: format!(
            "//! Negative case N6/{index}: the dependency has crypto; this crate calls only\n\
             //! its crypto-free function. Generated by `cargo xtask bench`; do not edit.\n\n\
             pub fn target(id: u32) -> String {{\n    vault::plain::label(id)\n}}\n"
        ),
        extra_files: Vec::new(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::bench::{names_crypto, CASES};

    fn cells(mode: &'static str) -> Vec<String> {
        CASES
            .iter()
            .filter_map(|case| build_dependency_shaped(mode, case, 0).expect("name-free"))
            .map(|m| format!("{} {}", m.family, m.parameter))
            .collect()
    }

    #[test]
    fn the_expected_cells_are_generated() {
        assert_eq!(cells("M8").len(), 12);
        assert_eq!(cells("M10").len(), 12);
        assert_eq!(
            cells("M9"),
            [
                "F-HASH SHA-256",
                "F-HASH SHA-512",
                "F-HASH-DEP SHA-1",
                "F-HASH-DEP MD5",
                "F-SYM AES-128",
                "F-SYM AES-256",
                "F-SYM ChaCha20",
                "F-PQC ML-KEM-768",
            ]
        );
    }

    #[test]
    fn every_labelled_line_names_nothing() {
        for mode in ["M8", "M9", "M10"] {
            for case in CASES {
                let Some(m) = build_dependency_shaped(mode, case, 0).unwrap() else {
                    continue;
                };
                let line = m.source.lines().nth(m.expected[0].line - 1).unwrap();
                assert_eq!(names_crypto(line, case), None, "{mode}: {line}");
                assert_eq!(m.expected[0].api, case.api);
            }
        }
    }

    #[test]
    fn vault_carries_every_cell_and_relay_no_crypto() {
        let vault = vault_source();
        assert_eq!(vault.matches("pub mod cell_").count(), 12);
        assert_eq!(vault.matches("pub mod generic_").count(), 8);
        assert!(vault.contains("pub mod plain"));
        let manifest = relay_manifest();
        for case in CASES {
            let krate = case.dep.split([' ', '=']).next().unwrap();
            assert!(
                !manifest.contains(&format!("{krate} =")),
                "relay depends on {krate}"
            );
        }
    }

    #[test]
    fn a_generic_module_imports_no_concrete_type() {
        let vault = vault_source();
        for (i, case) in CASES.iter().enumerate() {
            let start = format!("pub mod generic_{i} {{");
            let Some(at) = vault.find(&start) else {
                continue;
            };
            let block = &vault[at..at + vault[at..].find("\n}\n").unwrap()];
            let ty = crate::bench::type_of(case);
            assert!(!block.contains(ty), "generic_{i} names {ty}:\n{block}");
        }
    }

    #[test]
    fn n6_calls_only_the_crypto_free_function() {
        let m = build_n6(0, 0);
        assert_eq!(m.polarity, "negative");
        assert!(m.expected.is_empty());
        assert!(m.source.contains("vault::plain::label"));
        assert!(!m.source.contains("cell_"));
    }
}
